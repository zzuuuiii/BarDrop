import AppKit
import Combine
import UniformTypeIdentifiers

/// Verlauf der Zwischenablage (Nutzer, 31.10.2026): Was kopiert wird, landet als Datei in
/// einem eigenen Ordner. Ein Klick auf die Aktion „Zwischenablage“ zeigt ihn in der Ablage
/// wie einen angehefteten Ordner, neueste zuerst; ein Klick auf einen Eintrag kopiert ihn
/// wieder. Läuft nur, wenn er unter Einstellungen → Aktionen eingeschaltet ist: Erst dann
/// liest BarDrop die Zwischenablage, und erst dann fragt macOS nach der Erlaubnis dafür.
final class ClipboardHistory {
    static let shared = ClipboardHistory()

    /// So viele Einträge bleiben; ältere werden gelöscht
    static let limit = 50
    /// Dateien von einem anderen Laufwerk werden kopiert (auf demselben Laufwerk nur geklont,
    /// das kostet keinen Platz). Größere bleiben draußen, sonst füllte der Verlauf die Platte
    static let maxForeignFileSize: Int64 = 200 * 1024 * 1024

    static var defaultFolder: URL {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("BarDrop", isDirectory: true)
            .appendingPathComponent("Clipboard", isDirectory: true)
    }

    let folder: URL
    private let pasteboard: NSPasteboard
    private var timer: Timer?
    private var lastChange: Int {
        // Zähler der Zwischenablage gilt systemweit bis zum Neustart des Mac: gemerkt, damit
        // ein Neustart von BarDrop den unveränderten Inhalt nicht noch einmal aufnimmt
        didSet { if let key = changeKey { UserDefaults.standard.set(lastChange, forKey: key) } }
    }
    /// Nur für die echte Zwischenablage (Tests nutzen eigene)
    private var changeKey: String? { pasteboard.name == .general ? "clipboardHistoryLastChange" : nil }
    /// Inhalt des neuesten Eintrags: Dasselbe zweimal kopiert ergibt keinen zweiten Eintrag
    private var lastSignature: String?
    private var subscription: AnyCancellable?

    init(folder: URL = ClipboardHistory.defaultFolder, pasteboard: NSPasteboard = .general) {
        self.folder = folder
        self.pasteboard = pasteboard
        // changeCount verrät nichts über den Inhalt und löst keine Abfrage von macOS aus
        lastChange = pasteboard.changeCount
    }


    /// Folgt dem Schalter in den Einstellungen
    func follow(_ settings: AppSettings) {
        subscription = settings.$clipboardHistory.removeDuplicates()
            .receive(on: DispatchQueue.main)
            .sink { [weak self] on in on ? self?.start() : self?.stop() }
    }

    func start() {
        guard timer == nil else { return }
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        // Beim Einschalten gleich den jetzigen Inhalt aufnehmen: Dabei fragt macOS (falls es
        // fragt) direkt nach dem Klick auf den Schalter, nicht irgendwann später. Schon
        // aufgenommen (BarDrop neu gestartet, Inhalt unverändert): nicht noch einmal
        lastChange = changeKey.flatMap { UserDefaults.standard.object(forKey: $0) as? Int } ?? -1
        check()
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Zwischenablage geändert? Dann aufnehmen
    func check() {
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        record()
    }

    /// Typen, mit denen Apps sagen, dass etwas nicht in einen Verlauf gehört (Passwörter,
    /// nur kurz Kopiertes), siehe nspasteboard.org
    static let privateTypes: [NSPasteboard.PasteboardType] = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType"
    ].map { NSPasteboard.PasteboardType($0) }

    // MARK: Aufnehmen

    func record() {
        let types = pasteboard.types ?? []
        guard !types.isEmpty, !types.contains(where: Self.privateTypes.contains) else { return }
        let fileURLs = (pasteboard.readObjects(forClasses: [NSURL.self],
                                               options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
        // Aus dem eigenen Verlauf zurückkopiert: kein neuer Eintrag
        if !fileURLs.isEmpty, fileURLs.allSatisfy({ $0.deletingLastPathComponent().standardizedFileURL == folder.standardizedFileURL }) {
            return
        }
        if !fileURLs.isEmpty {
            let signature = "files:" + fileURLs.map(\.path).joined(separator: "\n")
            guard signature != lastSignature else { return }
            let saved = fileURLs.compactMap(copyFile)
            if !saved.isEmpty { finishRecord(signature) }
            return
        }
        let snapshot = PasteboardSnapshot(pasteboard)
        if let (data, ext) = snapshot.image ?? snapshot.objectImage {
            let signature = "image:\(data.count):\(data.prefix(64).base64EncodedString())"
            guard signature != lastSignature else { return }
            let name = snapshot.suggestedImageName ?? L("Image", "Bild")
            if write(data, name: "\(Self.baseName(name)).\(ext)") { finishRecord(signature) }
        } else if let link = snapshot.webURL, snapshot.text.map({ $0.trimmingCharacters(in: .whitespacesAndNewlines) == link.absoluteString }) ?? true {
            let signature = "link:" + link.absoluteString
            guard signature != lastSignature else { return }
            let plist = ["URL": link.absoluteString]
            guard let data = try? PropertyListSerialization.data(fromPropertyList: plist, format: .xml, options: 0) else { return }
            if write(data, name: "\(ContentImporter.sanitize(snapshot.urlTitle ?? link.host ?? "Link")).webloc") { finishRecord(signature) }
        } else if let text = snapshot.text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let signature = "text:" + text
            guard signature != lastSignature else { return }
            let title = text.trimmingCharacters(in: .whitespacesAndNewlines)
                .components(separatedBy: .newlines).first ?? text
            if write(Data(text.utf8), name: "\(ContentImporter.sanitize(String(title.prefix(40)))).txt") { finishRecord(signature) }
        }
    }

    private func finishRecord(_ signature: String) {
        lastSignature = signature
        prune()
    }

    /// Name ohne Endung (Bildnamen aus dem Web bringen ihre eigene mit)
    private static func baseName(_ name: String) -> String {
        let base = (name as NSString).deletingPathExtension
        return ContentImporter.sanitize(base.isEmpty ? name : base)
    }

    private func write(_ data: Data, name: String) -> Bool {
        let url = uniqueURL(for: name)
        do {
            try data.write(to: url)
            return true
        } catch {
            Diagnostics.shared.record("clipboard", "Eintrag nicht gespeichert: \(error.localizedDescription)")
            return false
        }
    }

    /// Kopierte Datei aufheben. Auf demselben Laufwerk legt das System nur einen Klon an
    /// (APFS), sonst nur kleine Dateien
    private func copyFile(_ source: URL) -> URL? {
        let keys: Set<URLResourceKey> = [.volumeIdentifierKey, .fileSizeKey, .isDirectoryKey]
        let values = try? source.resourceValues(forKeys: keys)
        let here = try? folder.resourceValues(forKeys: [.volumeIdentifierKey])
        let sameVolume = values?.volumeIdentifier.map { id in
            (here?.volumeIdentifier).map { ($0 as AnyObject).isEqual(id) } ?? false
        } ?? false
        if !sameVolume {
            guard values?.isDirectory != true,
                  Int64(values?.fileSize ?? .max) <= Self.maxForeignFileSize else { return nil }
        }
        let target = uniqueURL(for: source.lastPathComponent)
        do {
            try FileManager.default.copyItem(at: source, to: target)
            return target
        } catch {
            Diagnostics.shared.record("clipboard", "Datei nicht übernommen: \(error.localizedDescription)")
            return nil
        }
    }

    private func uniqueURL(for name: String) -> URL {
        let fm = FileManager.default
        var url = folder.appendingPathComponent(name)
        let base = (name as NSString).deletingPathExtension
        let ext = (name as NSString).pathExtension
        var n = 2
        while fm.fileExists(atPath: url.path) {
            url = folder.appendingPathComponent(ext.isEmpty ? "\(base) \(n)" : "\(base) \(n).\(ext)")
            n += 1
        }
        return url
    }

    /// Einträge, neueste zuerst (wie der Ordner in der Ablage sie zeigt)
    func entries() -> [URL] {
        let keys: [URLResourceKey] = [.addedToDirectoryDateKey, .creationDateKey]
        let urls = (try? FileManager.default.contentsOfDirectory(at: folder, includingPropertiesForKeys: keys,
                                                                 options: [.skipsHiddenFiles])) ?? []
        // Hineingekommen ist auf die Sekunde genau, angelegt auf Nanosekunden: das trennt
        // Einträge aus derselben Sekunde
        return urls.map { url -> (URL, Date, Date) in
            let values = try? url.resourceValues(forKeys: Set(keys))
            return (url, values?.addedToDirectoryDate ?? .distantPast, values?.creationDate ?? .distantPast)
        }
        .sorted { $0.1 != $1.1 ? $0.1 > $1.1 : $0.2 > $1.2 }
        .map(\.0)
    }

    /// Nur die neuesten `limit` Einträge behalten. Gelöscht wird endgültig: Es sind BarDrops
    /// eigene Kopien, sie gehören nicht in den Papierkorb des Nutzers
    private func prune() {
        for url in entries().dropFirst(Self.limit) {
            try? FileManager.default.removeItem(at: url)
        }
    }

    // MARK: Zurückkopieren

    /// Liegt die Datei im Verlauf?
    func contains(_ url: URL) -> Bool {
        url.deletingLastPathComponent().standardizedFileURL == folder.standardizedFileURL
    }

    /// Eintrag wieder in die Zwischenablage legen, so wie er kopiert wurde: Text als Text,
    /// Link als Link, Bild als Bild und Datei. Er rückt nach oben, wird aber nicht neu aufgenommen.
    /// Erst lesen, dann leeren: Lässt sich der Eintrag nicht lesen, bleibt die Zwischenablage, wie sie war.
    func copyBack(_ url: URL) {
        switch url.pathExtension.lowercased() {
        case "txt":
            if let text = try? String(contentsOf: url, encoding: .utf8) {
                pasteboard.clearContents()
                pasteboard.setString(text, forType: .string)
                lastSignature = "text:" + text
            }
        case "webloc":
            if let data = try? Data(contentsOf: url),
               let plist = try? PropertyListSerialization.propertyList(from: data, format: nil) as? [String: Any],
               let string = plist["URL"] as? String, let link = URL(string: string) {
                pasteboard.clearContents()
                pasteboard.writeObjects([link as NSURL])
                pasteboard.setString(string, forType: .string)
                lastSignature = "link:" + string
            }
        default:
            var objects: [NSPasteboardWriting] = [url as NSURL]
            if let image = NSImage(contentsOf: url), UTType(filenameExtension: url.pathExtension)?.conforms(to: .image) == true {
                objects.append(image)
            }
            pasteboard.clearContents()
            pasteboard.writeObjects(objects)
        }
        lastChange = pasteboard.changeCount
        bump(url)
    }

    /// Nach oben: Der Ordner sortiert nach dem Zeitpunkt, an dem eine Datei hineinkam
    private func bump(_ url: URL) {
        let fm = FileManager.default
        let parking = folder.deletingLastPathComponent().appendingPathComponent(".clipboard-\(UUID().uuidString)")
        guard (try? fm.moveItem(at: url, to: parking)) != nil else { return }
        if (try? fm.moveItem(at: parking, to: url)) == nil {
            try? fm.moveItem(at: parking, to: uniqueURL(for: url.lastPathComponent))
        }
    }
}
